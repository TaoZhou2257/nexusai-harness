/**
 * The thin profile link and the cipher seed, without booting dsh.
 */
import { mkdtempSync, mkdirSync, writeFileSync, readFileSync, readdirSync, lstatSync, symlinkSync, readlinkSync, existsSync, rmSync } from 'node:fs'
import { tmpdir } from 'node:os'
import { join } from 'node:path'
import { createRequire } from 'node:module'
const require = createRequire(import.meta.url)
const { materializeProfile } = require('../src/profile-link.cjs')
const { seedCipher } = require('../src/cipher-seed.cjs')
const yaml = require('yaml')
const jsTag = { tag: 'tag:yaml.org,2002:js', resolve: source => ({ js: source }) }

const failures = []
const check = (name, ok) => {
  if (ok) console.log(`ok  ${name}`)
  else { console.error(`FAIL ${name}`); failures.push(name) }
}

const root = mkdtempSync(join(tmpdir(), 'nexusai-layout-'))
const source = join(root, 'install')
const plugin = join(source, 'node_modules', '@toby', 'dsh-plugin-nexusai')
const im = join(source, 'node_modules', '@xmanrui', 'dsh-im')
const cli = join(source, 'node_modules', '@deepseek-ai', 'dsh', 'lib')
mkdirSync(plugin, { recursive: true })
mkdirSync(im, { recursive: true })
mkdirSync(cli, { recursive: true })
writeFileSync(join(plugin, 'package.json'), '{"name":"@toby/dsh-plugin-nexusai"}\n')
writeFileSync(join(im, 'package.json'), '{"name":"@xmanrui/dsh-im"}\n')
writeFileSync(join(cli, 'bin.js'), '// cli\n')
writeFileSync(join(source, 'package.json'), '{"name":"dsh-profile-nexusai"}\n')
writeFileSync(join(source, 'cordis.patch.yml'), 'baseUrl: only\n')

const home = join(root, 'home')
const first = materializeProfile({
  home, profileName: 'nexusai', sourceProfile: source, appVersion: '0.1.14', runtimeVersion: 'rt', log() {},
})
const modules = join(home, 'profiles', 'nexusai', 'node_modules')
const linked = join(modules, '@toby', 'dsh-plugin-nexusai')
check('node_modules is a real directory', lstatSync(modules).isDirectory() && !lstatSync(modules).isSymbolicLink())
check('plugin link points at the installation', lstatSync(linked).isSymbolicLink() && readlinkSync(linked) === plugin)
check('IM bundle link points at the installation', readlinkSync(join(modules, '@xmanrui', 'dsh-im')) === im)
check('cli stays in the installation', first.cli === join(cli, 'bin.js') && !existsSync(join(modules, '@deepseek-ai')))
check('patch copied without being the install tree', readFileSync(join(home, 'profiles', 'nexusai', 'cordis.patch.yml'), 'utf8') === 'baseUrl: only\n')

const marker = join(home, 'profiles', 'nexusai', '.nexusai-desktop-runtime')
writeFileSync(marker, '0.0.0+old\n')
rmSync(modules, { recursive: true, force: true })
symlinkSync(source, modules, 'dir')
const sentinel = join(source, 'node_modules', 'SENTINEL')
writeFileSync(sentinel, 'keep\n')
materializeProfile({
  home, profileName: 'nexusai', sourceProfile: source, appVersion: '0.1.14', runtimeVersion: 'rt', log() {},
})
check('old whole-tree link is replaced', lstatSync(modules).isDirectory() && !lstatSync(modules).isSymbolicLink())
check('replacing the link does not delete the installation', readFileSync(sentinel, 'utf8') === 'keep\n')

let refused = false
const foreign = join(root, 'foreign')
mkdirSync(join(foreign, 'profiles', 'nexusai', 'node_modules'), { recursive: true })
try {
  materializeProfile({
    home: foreign, profileName: 'nexusai', sourceProfile: source, appVersion: '0.1.14', runtimeVersion: 'rt', log() {},
  })
} catch {
  refused = true
}
check('a real node_modules this app did not create is refused', refused)

const factory = ({ notice = '2026-09-28.1', baseUrl = 'http://a', extra = '' } = {}) => [
  '# Generated by scripts/prepare-runtime.mjs — do not edit in the bundle.',
  '- id: ui-settings-account',
  '  disabled: true',
  '- id: ui-sidebar-browser',
  '  disabled: false',
  '- id: ui-settings-general',
  "  name: '@deepseek-ai/dsh-client-ui-settings-general'",
  '  config:',
  `    welcomeNoticeVersion: '${notice}'`,
  '- id: locale',
  "  name: '@deepseek-ai/dsh-client-locale'",
  '  config:',
  "    preference: 'zh'",
  extra,
  '- insert:',
  '    - id: workspace-dependencies',
  "      name: '@deepseek-ai/dsh-tool-workspace-dependencies'",
  '      config:',
  '        source: !!js "process.env.DSH_BUNDLED_PRIMARY_RUNTIME"',
  '    - id: nexusai',
  "      name: '@toby/dsh-plugin-nexusai'",
  '      config:',
  `        baseUrl: '${baseUrl}'`,
].filter(line => line !== '').join('\n') + '\n'
const userRows = [
  '- id: llm-pi-ai',
  '  config:',
  '    providers:',
  '      acme-gateway:',
  '        api: openai-completions',
  '        baseURL: https://relay.example/v1',
  '        apiKeyEnv: llm-pi-ai/acme-gateway',
  '        models:',
  '          - id: acme-large',
  '- insert:',
  '    - id: custom-mcp-notes-1a2b',
  "      name: '@deepseek-ai/dsh-mcp-client'",
  '      config:',
  '        serverName: custom-mcp-notes-1a2b',
  '',
].join('\n')
const patchSource = join(root, 'patch-install')
mkdirSync(join(patchSource, 'node_modules', '@toby', 'dsh-plugin-nexusai'), { recursive: true })
mkdirSync(join(patchSource, 'node_modules', '@xmanrui', 'dsh-im'), { recursive: true })
mkdirSync(join(patchSource, 'node_modules', '@deepseek-ai', 'dsh', 'lib'), { recursive: true })
writeFileSync(join(patchSource, 'node_modules', '@deepseek-ai', 'dsh', 'lib', 'bin.js'), '// cli\n')
const patchHome = join(root, 'patch-home')
const patchFile = join(patchHome, 'profiles', 'nexusai', 'cordis.patch.yml')
const run = (version) => materializeProfile({
  home: patchHome, profileName: 'nexusai', sourceProfile: patchSource, appVersion: version, runtimeVersion: 'rt', log() {},
})
const rows = () => yaml.parse(readFileSync(patchFile, 'utf8'), { customTags: [jsTag] })
const row = (id) => rows().find(item => item.id === id)
const insertIds = () => rows().filter(item => Array.isArray(item.insert)).map(item => item.insert.map(entry => entry.id).join(','))

writeFileSync(join(patchSource, 'cordis.patch.yml'), factory())
run('0.1.21')
check('fresh home gets the bundle patch as is', readFileSync(patchFile, 'utf8') === factory())

writeFileSync(patchFile, `${readFileSync(patchFile, 'utf8').replace("preference: 'zh'", "preference: 'en'").replace(
  "welcomeNoticeVersion: '2026-09-28.1'", "welcomeNoticeVersion: '2026-09-28.1'\n    theme: dark",
)}${userRows}`)
run('0.1.21')
check('restart keeps the custom model API row', row('llm-pi-ai')?.config?.providers?.['acme-gateway']?.baseURL === 'https://relay.example/v1')
check('restart keeps the custom connector insert', insertIds().includes('custom-mcp-notes-1a2b'))
check('restart keeps a changed setting', row('locale')?.config?.preference === 'en' && row('ui-settings-general')?.config?.theme === 'dark')

writeFileSync(join(patchSource, 'cordis.patch.yml'), factory({ notice: '2026-11-01.1', baseUrl: 'http://b', extra: '- id: added-row\n  disabled: true' })
  .replace('- id: ui-sidebar-browser\n  disabled: false\n', ''))
run('0.1.22')
check('upgrade keeps the custom model API row', row('llm-pi-ai')?.config?.providers?.['acme-gateway']?.models?.[0]?.id === 'acme-large')
check('upgrade keeps the custom connector insert', insertIds().includes('custom-mcp-notes-1a2b'))
check('upgrade takes new factory values the user never changed',
  row('ui-settings-general')?.config?.welcomeNoticeVersion === '2026-11-01.1'
  && rows().some(item => Array.isArray(item.insert) && item.insert.some(entry => entry.config?.baseUrl === 'http://b')))
check('upgrade keeps values the user changed', row('locale')?.config?.preference === 'en' && row('ui-settings-general')?.config?.theme === 'dark')
check('upgrade adds and drops factory rows', row('added-row')?.disabled === true && row('ui-sidebar-browser') === undefined)
check('js expressions are written back unevaluated', readFileSync(patchFile, 'utf8').includes('source: !!js "process.env.DSH_BUNDLED_PRIMARY_RUNTIME"'))

rmSync(join(patchHome, 'profiles', 'nexusai', '.nexusai-factory-patch.yml'))
writeFileSync(patchFile, `${factory()}${userRows}`)
run('0.1.22')
check('a home without a baseline keeps user rows', row('llm-pi-ai') !== undefined && insertIds().includes('custom-mcp-notes-1a2b'))
check('a home without a baseline takes the new factory values', row('ui-settings-general')?.config?.welcomeNoticeVersion === '2026-11-01.1')

const stable = readFileSync(patchFile, 'utf8')
run('0.1.22')
check('a second start with the same bundle leaves the patch alone', readFileSync(patchFile, 'utf8') === stable)

writeFileSync(patchFile, `${stable}- id: nexusai\n  config:\n    baseUrl: 'http://b'\n    note: kept\n`)
run('0.1.22')
writeFileSync(join(patchSource, 'cordis.patch.yml'), factory({ notice: '2026-11-01.1', baseUrl: 'http://b', extra: '- id: added-row\n  disabled: true' })
  .replace('- id: ui-sidebar-browser\n  disabled: false\n', '')
  .replace('    - id: nexusai', "    - id: skill-office\n      name: '@deepseek-ai/dsh-skill-office'\n    - id: nexusai"))
for (const withBaseline of [true, false]) {
  if (!withBaseline) {
    writeFileSync(patchFile, `${stable}- id: nexusai\n  config:\n    baseUrl: 'http://b'\n    note: kept\n`)
    rmSync(join(patchHome, 'profiles', 'nexusai', '.nexusai-factory-patch.yml'))
  }
  run('0.1.23')
  const all = rows()
  const factoryInsert = all.findIndex(item => Array.isArray(item.insert) && item.insert.some(entry => entry.id === 'nexusai'))
  const override = all.findIndex(item => item.id === 'nexusai')
  const label = withBaseline ? 'with a baseline' : 'without a baseline'
  check(`a changed factory insert replaces the old one (${label})`,
    all.filter(item => Array.isArray(item.insert) && item.insert.some(entry => entry.id === 'nexusai')).length === 1
    && insertIds().includes('workspace-dependencies,skill-office,nexusai'))
  check(`a user override stays after the insert it targets (${label})`, factoryInsert >= 0 && override > factoryInsert && all[override].config.note === 'kept')
}

writeFileSync(patchFile, '- id: [broken\n')
run('0.1.22')
const backups = readdirSync(join(patchHome, 'profiles', 'nexusai')).filter(name => name.startsWith('cordis.patch.yml.bak-'))
check('an unreadable patch is backed up and replaced', backups.length === 1 && row('added-row')?.disabled === true)

const seedHome = join(root, 'secrets')
mkdirSync(seedHome, { recursive: true })
const seedFile = join(root, 'cipher-seed.json')
writeFileSync(seedFile, JSON.stringify({ seedVersion: 1, aesKey: 'k', aesIv: 'v' }))
writeFileSync(join(seedHome, '.credentials.yaml'), 'version: 1\nrecords:\n  nexusai/session:\n    kind: grant\n    payload:\n      token: stay\n')
check('first seed writes the cipher', seedCipher({ home: seedHome, seedFile, log() {} }) === 'written')
const written = readFileSync(join(seedHome, '.credentials.yaml'), 'utf8')
check('session record survives the cipher write', written.includes('nexusai/session') && written.includes('token: stay'))
check('cipher grant is in the credentials file', written.includes('nexusai/cipher') && written.includes('aesKey: k') && written.includes('aesIv: v'))
check('same seed version is kept', seedCipher({ home: seedHome, seedFile, log() {} }) === 'skipped')
writeFileSync(seedFile, JSON.stringify({ seedVersion: 2, aesKey: 'k2', aesIv: 'v2' }))
check('a newer seed replaces the record', seedCipher({ home: seedHome, seedFile, log() {} }) === 'written')
check('replaced record carries the new key', readFileSync(join(seedHome, '.credentials.yaml'), 'utf8').includes('aesKey: k2'))

if (failures.length > 0) {
  console.error(`${failures.length} failed`)
  process.exit(1)
}
console.log('profile layout checks passed')
